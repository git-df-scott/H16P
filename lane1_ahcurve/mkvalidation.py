w("## What the engine is")
w("")
w("`ahcurve.c` integrates the quadratic field with Dormand-Prince 5(4) in")
w("coordinates re-expanded about the focus, so the focus sits at the origin and")
w("the coordinate magnitude *is* the orbit radius.  The section is a ray from the")
w("focus.  A return is detected by accumulating the signed angle about the origin")
w("and stopping when it reaches 2*pi, bisecting on the final step; at that instant")
w("the orbit is on the ray by construction.")
w("")
w("Three bugs from `audit/fable_engine/REVIEW_engine.md` are addressed structurally:")
w("")
w("| ID | The bug | What this engine does |")
w("|---|---|---|")
w("| A1 | `atol = 1e-14*(1+r)` is an absolute floor, so sign changes below ~1e-13 are noise | `atol = 1e-16*s`, `rtol = 1e-12`, plus the two-tolerance noise floor of PROTOCOL rule 1 on every reported quantity |")
w("| A2 | step tolerance scaled by the focus offset rather than the orbit radius | the field is re-expanded about the focus before integration; the caller never passes a global coordinate |")
w("| A3 | a dead third disjunct in the ray-crossing filter accepts wrong-direction crossings | there is no crossing filter: the stopping condition is the accumulated angle reaching 2*pi |")
w("| B1 | 40 radii over 6.5 decades cannot resolve cycles closer than 1.5x | 300 log-spaced section points per nest, with local refinement |")
w("| B2 | one failed radius truncates the whole nest | failures are marked NaN per point and never bracket; `s_max` is recorded separately |")
w("")
w("## V1-V2  Cycle count and position in the primary nest")
