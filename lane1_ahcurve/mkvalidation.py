w("300 log-spaced section points on the paper's own section, at the published")
w("parameters.  A sign change counts only when both endpoint magnitudes clear the")
w("two-tolerance noise estimate `10*|D(rtol 1e-12) - D(rtol 1e-10)| + 5e-12*s`.")
